#!/usr/bin/env python3
"""Freeze the text-only pilot's word boundaries to the API's Python 3.12.

Run with Python 3.12 (Unicode 15.0.0), optionally with --check. A backend
Python/Unicode upgrade requires reviewing and regenerating this matcher,
then rerunning native parser and browser input/draft-preservation controls.
Browser Unicode property escapes must not substitute for this versioned data.
"""
from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "app" / "web" / "src" / "lib" / "chatPilotPythonWord.ts"
PYTHON_VERSION = (3, 12)
UNICODE_VERSION = "15.0.0"


def render() -> str:
    if (
        sys.version_info[:2] != PYTHON_VERSION
        or unicodedata.unidata_version != UNICODE_VERSION
    ):
        raise ValueError("Requires the API's Python 3.12 / Unicode 15.0.0; do not use browser data.")

    ranges: list[tuple[int, int]] = []
    start: int | None = None
    for codepoint in range(sys.maxunicode + 2):
        word = codepoint <= sys.maxunicode and (
            chr(codepoint).isalnum() or codepoint == ord("_")
        )
        if word and start is None:
            start = codepoint
        elif not word and start is not None:
            ranges.append((start, codepoint - 1))
            start = None

    def escape(codepoint: int) -> str:
        return rf"\u{{{codepoint:x}}}"

    character_class = "".join(
        escape(first) if first == last else f"{escape(first)}-{escape(last)}"
        for first, last in ranges
    )
    return (
        "// Generated by scripts/gen-chat-pilot-unicode.py; do not edit.\n"
        "// Python 3.12 / Unicode 15.0.0 re \\w: str.isalnum() plus underscore.\n"
        "// Review/regenerate with the API Python pin; never use browser Unicode properties.\n"
        f"export const PYTHON_WORD_RE = /^[{character_class}]$/u;\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing.")
    args = parser.parse_args(argv)
    try:
        rendered = render().encode("utf-8")
    except ValueError as exc:
        parser.error(str(exc))
    if args.check:
        if not TARGET.exists() or TARGET.read_bytes() != rendered:
            print("Pilot Unicode matcher is stale; regenerate with Python 3.12.", file=sys.stderr)
            return 1
        return 0
    TARGET.write_bytes(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
